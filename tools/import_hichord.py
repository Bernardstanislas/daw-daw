"""Copies the HiChord instrument + TightKit samples into daw-daw and writes
samples/manifest.json and src/dsp/sample_data.rs (embedded sample table).

Usage: python3 -I import_hichord.py <hichord_ctx_dir> <daw_core_crate_dir>  (e.g. crates/daw-core)
"""
import json
import math
import shutil
import sys
from pathlib import Path

# Display name, slug and pitch (Hz) we trust after measuring (see measure_pitch.py).
INSTRUMENTS = {
    "Strings": ("strings", 261.41),
    "Clarinet": ("clarinet", 524.02),
    "Cellos": ("cellos", 520.55),
    "Acoustic": ("acoustic-guitar", 523.03),
    "Brass": ("brass", 523.32),
    "Piano Upr": ("upright-piano", 524.35),
    "Vibraph": ("vibraphone", 523.25),
    "Violins": ("violins", 525.71),
    "Vox Ahh": ("vox-ahh", 524.2),
    "Retro EP": ("retro-ep", 523.06),
    "Harp": ("harp", 261.47),
    "Viola": ("viola", 260.63),
    "Humming": ("humming", 272.01),
    "Robbo": ("robbo", 261.69),
    "Shutter": ("shutter", 1046.56),
    "Flute": ("flute", 503.43),
    "Buzz Org": ("buzz-organ", 131.81),
    "Organ": ("organ", 65.81),
    "Tine EP": ("tine-ep", 261.95),
    "Horns": ("horns", 526.93),
    "E Guitar": ("electric-guitar", 262.10),
    "GrandPno": ("grand-piano", 525.06),
}
PRETTY = {
    "Acoustic": "Acoustic Guitar",
    "Piano Upr": "Upright Piano",
    "Vibraph": "Vibraphone",
    "Buzz Org": "Buzz Organ",
    "E Guitar": "Electric Guitar",
    "GrandPno": "Grand Piano",
}

# TightKit: file stem → (slug, display name, GM note)
DRUMS = {
    "tightkit_kick": ("kick", "Kick", 36),
    "tightkit_snare": ("snare", "Snare", 38),
    "tightkit_unused0": ("clap", "Clap", 39),
    "tightkit_tom": ("low-tom", "Low Tom", 41),
    "tightkit_chat": ("closed-hat", "Closed Hat", 42),
    "tightkit_ohat": ("open-hat", "Open Hat", 46),
    "tightkit_unused1": ("conga", "Conga", 48),
    "tightkit_unused4": ("shaker", "Shaker", 70),
}


def midi_of(hz: float) -> float:
    return 69 + 12 * math.log2(hz / 440.0)


def main():
    ctx = Path(sys.argv[1])
    out_root = Path(sys.argv[2])
    re_dir = ctx / "re"
    samples_src = ctx / "hc_updater" / "samples"
    dst = out_root / "samples"
    (dst / "instruments").mkdir(parents=True, exist_ok=True)
    (dst / "drums").mkdir(parents=True, exist_ok=True)

    doc = json.load(open(re_dir / "sounds.json"))
    adsr = doc["adsr_presets"]
    instruments = []
    for s in doc["sounds"]:
        smp = s.get("sample") or {}
        wav = smp.get("wav")
        if not wav or s["name"] not in INSTRUMENTS:
            continue
        name = Path(wav.split(" ")[0]).name
        src = samples_src / name
        if not src.exists():
            src = re_dir / "sounds_tools" / name
        slug, hz = INSTRUMENTS[s["name"]]
        shutil.copyfile(src, dst / "instruments" / f"{slug}.wav")
        env_name = s.get("default_adsr_browse")
        env = adsr.get(env_name, adsr["TOUCH"]) if isinstance(env_name, str) else adsr["TOUCH"]
        frames = smp["frames"]
        instruments.append(
            {
                "id": slug,
                "name": PRETTY.get(s["name"], s["name"]),
                "file": f"instruments/{slug}.wav",
                "rootMidi": round(midi_of(hz), 3),
                "loopStart": smp["loop_start_frame"],
                "loopEnd": smp["loop_end_frame"],
                "crossfade": int(round(smp["crossfade"] * frames)),
                "gain": s.get("gain", 1.0),
                "envelope": env_name if isinstance(env_name, str) else "TOUCH",
                "attack": env["attack"],
                "decay": env["decay"],
                "sustain": env["sustain"],
                "release": env["release"],
            }
        )

    drums = []
    for stem, (slug, label, note) in DRUMS.items():
        shutil.copyfile(re_dir / "drums" / f"{stem}.wav", dst / "drums" / f"{slug}.wav")
        drums.append({"id": slug, "name": label, "file": f"drums/{slug}.wav", "note": note})

    manifest = {
        "source": "HiChord 3.0 sample set (instruments + TightKit). See NOTICE.md.",
        "sampleRate": 48000,
        "instruments": instruments,
        "drums": drums,
    }
    (dst / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")

    # Generated Rust table (include_bytes needs literal paths).
    lines = [
        "//! GENERATED by tools/import_hichord.py — do not edit by hand.",
        "//! Embedded sample set; metadata lives in samples/manifest.json.",
        "",
        "pub struct InstrumentSample {",
        "    pub id: &'static str,",
        "    pub name: &'static str,",
        "    pub wav: &'static [u8],",
        "    pub root_midi: f32,",
        "    pub loop_start: usize,",
        "    pub loop_end: usize,",
        "    pub crossfade: usize,",
        "    pub gain: f32,",
        "    /// Default envelope (seconds / level): attack, decay, sustain, release.",
        "    pub adsr: [f32; 4],",
        "}",
        "",
        "pub struct DrumSample {",
        "    pub id: &'static str,",
        "    pub name: &'static str,",
        "    pub wav: &'static [u8],",
        "    pub note: u8,",
        "}",
        "",
        "pub static INSTRUMENTS: &[InstrumentSample] = &[",
    ]
    for i in instruments:
        lines.append(
            f'    InstrumentSample {{ id: "{i["id"]}", name: "{i["name"]}", '
            f'wav: include_bytes!("../../samples/{i["file"]}"), root_midi: {i["rootMidi"]}, '
            f'loop_start: {i["loopStart"]}, loop_end: {i["loopEnd"]}, crossfade: {i["crossfade"]}, '
            f'gain: {i["gain"]}, adsr: [{i["attack"]}, {i["decay"]}, {i["sustain"]}, {i["release"]}] }},'
        )
    lines.append("];")
    lines.append("")
    lines.append("pub static DRUMS: &[DrumSample] = &[")
    for d in drums:
        lines.append(
            f'    DrumSample {{ id: "{d["id"]}", name: "{d["name"]}", '
            f'wav: include_bytes!("../../samples/{d["file"]}"), note: {d["note"]} }},'
        )
    lines.append("];")
    lines.append("")
    lines.append("pub const INSTRUMENT_NAMES: &[&str] = &[")
    for i in instruments:
        lines.append(f'    "{i["name"]}",')
    lines.append("];")
    lines.append("")
    lines.append("/// One preset per sound, with the envelope the sound was designed with.")
    lines.append("pub static INSTRUMENT_PRESETS: &[super::Preset] = &[")
    for k, i in enumerate(instruments):
        lines.append(
            f'    super::Preset {{ name: "{i["name"]}", values: &[("sound", {k}.0), ("attack", {i["attack"]}), '
            f'("decay", {i["decay"]}), ("sustain", {i["sustain"]}), ("release", {i["release"]})] }},'
        )
    lines.append("];")
    lines.append("")
    lines.append("pub const DRUM_NOTE_NAMES: &[(u8, &str)] = &[")
    for d in sorted(drums, key=lambda d: d["note"]):
        lines.append(f'    ({d["note"]}, "{d["name"]}"),')
    lines.append("];")
    (out_root / "src" / "dsp" / "sample_data.rs").write_text("\n".join(lines) + "\n")
    print(f"{len(instruments)} instruments, {len(drums)} drums → {dst}")


if __name__ == "__main__":
    main()
